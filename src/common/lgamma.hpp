static const double
C1  =  4.16666666666666019037e-02, /* 0x3FA55555, 0x5555554C */
C2  = -1.38888888888741095749e-03, /* 0xBF56C16C, 0x16C15177 */
C3  =  2.48015872894767294178e-05, /* 0x3EFA01A0, 0x19CB1590 */
C4  = -2.75573143513906633035e-07, /* 0xBE927E4F, 0x809C52AD */
C5  =  2.08757232129817482790e-09, /* 0x3E21EE9E, 0xBDB4B1C4 */
C6  = -1.13596475577881948265e-11; /* 0xBDA8FAE9, 0xBE8838D4 */
// clang-format on

static double
bionic_cos(double x, double y) {
  double_t hz, z, r, w;
  z = x * x;
  w = z * z;
  r = z * (C1 + z * (C2 + z * C3)) + w * w * (C4 + z * (C5 + z * C6));
  hz = 0.5 * z;
  w = 1.0 - hz;
  return w + (((1.0 - w) - hz) + (z * r - x * y));
}

// clang-format off
static const double
S1  = -1.66666666666666324348e-01, /* 0xBFC55555, 0x55555549 */
S2  =  8.33333333332248946124e-03, /* 0x3F811111, 0x1110F8A6 */
S3  = -1.98412698298579493134e-04, /* 0xBF2A01A0, 0x19C161D5 */
S4  =  2.75573137070700676789e-06, /* 0x3EC71DE3, 0x57B1FE7D */
S5  = -2.50507602534068634195e-08, /* 0xBE5AE5E6, 0x8A2B9CEB */
S6  =  1.58969099521155010221e-10; /* 0x3DE5D93A, 0x5ACFD57C */
// clang-format on

static inline double
bionic_sin(double x, double y, int iy) {
  double_t z, r, v, w;

  z = x * x;
  w = z * z;
  r = S2 + z * (S3 + z * S4) + z * w * (S5 + z * S6);
  v = z * x;
  if (iy == 0)
    return x + v * (S1 + z * r);
  else
    return x - ((z * (0.5 * y - v * r) - y) - v * S1);
}

/* sin(pi*x) assuming x > 2^-100, if sin(pi*x)==0 the sign is arbitrary */
static double
sin_pi(double x) {
  int n;

  /* spurious inexact if odd int */
  x = 2.0 * (x * 0.5 - std::floor(x * 0.5)); /* x mod 2.0 */

  n = (int)(x * 4.0);
  n = (n + 1) / 2;
  x -= n * 0.5f;
  x *= pi;

  switch (n) {
  default: /* case 4: */
  case 0:
    return bionic_sin(x, 0.0, 0);
  case 1:
    return bionic_cos(x, 0.0);
  case 2:
    return bionic_sin(-x, 0.0, 0);
  case 3:
    return -bionic_cos(x, 0.0);
  }
}

[[nodiscard]] double
lgamma(double x) {
  union {
    double f;
    uint64_t i;
  } u = {x};
  double_t t, y, z, nadj{}, p, p1, p2, p3, q, r, w;
  uint32_t ix;
  int sign, i;

  /* purge off +-inf, NaN, +-0, tiny and negative arguments */
  // *signgamp = 1;
  sign = u.i >> 63;
  ix = u.i >> 32 & 0x7fffffff;
  if (ix >= 0x7ff00000)
    return x * x;
  if (ix < (0x3ff - 70) << 20) { /* |x|<2**-70, return -log(|x|) */
    if (sign) {
      x = -x;
      // *signgamp = -1;
    }
    return -std::log(x);
  }
  if (sign) {
    x = -x;
    t = sin_pi(x);
    if (t == 0.0) /* -integer */
      return 1.0 / (x - x);

    /// ADS: not needed below
    // if (t > 0.0)
    //   *signgamp = -1;
    // else
    //   t = -t;

    if (t <= 0.0)
      t = -t;

    nadj = std::log(pi / (t * x));
  }

  /* purge off 1 and 2 */
  if ((ix == 0x3ff00000 || ix == 0x40000000) && (uint32_t)u.i == 0)
    r = 0;
  /* for x < 2.0 */
  else if (ix < 0x40000000) {
    if (ix <= 0x3feccccc) { /* lgamma(x) = lgamma(x+1)-log(x) */
      r = -std::log(x);
      if (ix >= 0x3FE76944) {
        y = 1.0 - x;
        i = 0;
      }
      else if (ix >= 0x3FCDA661) {
        y = x - (tc - 1.0);
        i = 1;
      }
      else {
        y = x;
        i = 2;
      }
    }
    else {
      r = 0.0;
      if (ix >= 0x3FFBB4C3) { /* [1.7316,2] */
        y = 2.0 - x;
        i = 0;
      }
      else if (ix >= 0x3FF3B4C4) { /* [1.23,1.73] */
        y = x - tc;
        i = 1;
      }
      else {
        y = x - 1.0;
        i = 2;
      }
    }
    switch (i) {
    case 0:
      z = y * y;
      p1 = a0 + z * (a2 + z * (a4 + z * (a6 + z * (a8 + z * a10))));
      p2 = z * (a1 + z * (a3 + z * (a5 + z * (a7 + z * (a9 + z * a11)))));
      p = y * p1 + p2;
      r += (p - 0.5 * y);
      break;
    case 1:
      z = y * y;
      w = z * y;
      p1 = t0 + w * (t3 + w * (t6 + w * (t9 + w * t12))); /* parallel comp */
      p2 = t1 + w * (t4 + w * (t7 + w * (t10 + w * t13)));
      p3 = t2 + w * (t5 + w * (t8 + w * (t11 + w * t14)));
      p = z * p1 - (tt - w * (p2 + y * p3));
      r += tf + p;
      break;
    case 2:
      p1 = y * (u0 + y * (u1 + y * (u2 + y * (u3 + y * (u4 + y * u5)))));
      p2 = 1.0 + y * (v1 + y * (v2 + y * (v3 + y * (v4 + y * v5))));
      r += -0.5 * y + p1 / p2;
    }
  }
  else if (ix < 0x40200000) { /* x < 8.0 */
    i = (int)x;
    y = x - (double)i;
    p =
      y * (s0 + y * (s1 + y * (s2 + y * (s3 + y * (s4 + y * (s5 + y * s6))))));
    q = 1.0 + y * (r1 + y * (r2 + y * (r3 + y * (r4 + y * (r5 + y * r6)))));
    r = 0.5 * y + p / q;
    z = 1.0; /* lgamma(1+s) = log(s) + lgamma(s) */
    switch (i) {
    case 7:
      z *= y + 6.0; /* FALLTHRU */
    case 6:
      z *= y + 5.0; /* FALLTHRU */
    case 5:
      z *= y + 4.0; /* FALLTHRU */
    case 4:
      z *= y + 3.0; /* FALLTHRU */
    case 3:
      z *= y + 2.0; /* FALLTHRU */
      r += std::log(z);
      break;
    }
  }
  else if (ix < 0x43900000) { /* 8.0 <= x < 2**58 */
    t = std::log(x);
    z = 1.0 / x;
    y = z * z;
    w = w0 + z * (w1 + y * (w2 + y * (w3 + y * (w4 + y * (w5 + y * w6)))));
    r = (x - 0.5) * (t - 1.0) + w;
  }
  else /* 2**58 <= x <= inf */
    r = x * (std::log(x) - 1.0);
  if (sign)
    r = nadj - r;
  return r;
}

